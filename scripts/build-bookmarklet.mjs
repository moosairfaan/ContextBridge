import * as esbuild from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const entry = join(root, "src/bookmarklet/entry.ts");
const outDir = join(root, "src/bookmarklet");
const generatedHrefPath = join(outDir, "generatedHref.ts");
const rawOutPath = join(outDir, "bookmarklet.iife.js");

const MAX_REASONABLE_BYTES = 40_000;

const result = await esbuild.build({
  absWorkingDir: root,
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["es2018"],
  write: false,
  logLevel: "silent",
  // Keep the bookmarklet free of React / app UI.
  packages: "bundle",
  treeShaking: true,
});

const outputFile = result.outputFiles?.[0];
if (!outputFile) {
  throw new Error("Bookmarklet build produced no output");
}

const iifeCode = Buffer.from(outputFile.contents).toString("utf8").trim();
const bookmarkletHref = `javascript:${encodeURIComponent(iifeCode)}`;
const byteSize = Buffer.byteLength(iifeCode, "utf8");
const hrefByteSize = Buffer.byteLength(bookmarkletHref, "utf8");

mkdirSync(outDir, { recursive: true });
writeFileSync(rawOutPath, `${iifeCode}\n`, "utf8");

const generatedSource = `/* Generated by scripts/build-bookmarklet.mjs — do not edit by hand. */
export const BOOKMARKLET_IIFE = ${JSON.stringify(iifeCode)};
export const BOOKMARKLET_HREF = ${JSON.stringify(bookmarkletHref)};
export const BOOKMARKLET_BYTE_SIZE = ${byteSize} as const;
`;

writeFileSync(generatedHrefPath, generatedSource, "utf8");

console.log(
  `[ContextBridge] Bookmarklet built: ${byteSize.toLocaleString()} bytes IIFE, ${hrefByteSize.toLocaleString()} bytes javascript: URL`
);

if (byteSize > MAX_REASONABLE_BYTES) {
  console.warn(
    `[ContextBridge] Warning: bookmarklet IIFE is ${byteSize} bytes (target < ${MAX_REASONABLE_BYTES}).`
  );
}
